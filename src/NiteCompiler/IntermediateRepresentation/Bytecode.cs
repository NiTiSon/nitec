	LoadS16 = 0b1010,
	LoadS32 = 0b1011,
	LoadS64 = 0b1100,
	Add = 0x10,
	Sub = 0x11,
	Mul = 0x12,
	Div = 0x13,
	Mod = 0x14,
	And = 0x15,
	Or = 0x16,
	Xor = 0x17,
	Not = 0x18,
	Negate = 0x19,

	BrCond = 0xFA,
	Br = 0xFB,
	Ret = 0xFC,
	RetVoid = 0xFD,
	Label = 0xFE,
	TwoByteInstruction = 0xFF,
